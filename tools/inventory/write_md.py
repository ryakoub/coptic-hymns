"""Writes docs/app/hymn-inventory.md from inventory.json."""
import json, os
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.normpath(os.path.join(HERE, '../..'))
hymns = json.load(open(os.path.join(SITE, 'docs/app/hymn-inventory.json')))
library = json.load(open(os.path.join(SITE, 'catalog/library.json')))
groups = [(g, c) for g in library['groups'] for c in g['collections'] if g['id'] != 'programs']

STAGE = {'kg': 'KG', 'grades-1-2': 'Gr 1–2', 'grades-3-4': 'Gr 3–4', 'grades-5-6': 'Gr 5–6', 'ms': 'Middle', 'hs': 'High',
         'college': 'College', 'graduates': 'Graduates', 'servants': 'Servants', 'cana-family': 'Cana families',
         'simeon-elders': 'Elders', 'didymus': 'Didymus', 'special-needs': 'Special needs', 'adult-learners': 'Adults'}
LEVEL = {'1': 'L1', '2': 'L2', 'gifted': 'gifted', 'required': 'required'}

by_coll = defaultdict(list)
for h in hymns:
    by_coll[h['places'][0]['collection'] if h['places'] else 'none'].append(h)

c = Counter(h['status'] for h in hymns)
years = Counter(h['video']['year'] for h in hymns if h['video'])
L = []
L.append('# Hymn inventory\n')
L.append('Every hymn in the app, plus every Mahragan hymn on the youth-bishopric YouTube channel '
         '(https://www.youtube.com/@youth-bishopric, Mahragan Al-Keraza 2022–2026). Generated by `tools/inventory/`; '
         'edit the rules there, not this file.\n')
L.append(f"- **{len(hymns)} hymns**: {c['in app']} in the app, {c['new']} new from the channel.")
L.append('- When the channel has a hymn more than once (several years, stages or levels), the most recent video is kept; the others are counted under *Versions*.')
L.append('- *Status* "in app" means the hymn is already in `content/`, whatever recording it uses. Its titles and places here are its own: change them with `tools/titles.py` (a spreadsheet), not in this file.')
L.append('- ⚠ marks a placement or match to confirm. 🔒 means the newest video is unavailable (`tools/inventory/unavailable.txt`), so an older one is listed or the hymn needs another source.')
L.append('- Year of the kept video: ' + ', '.join(f'{y}: {n}' for y, n in sorted(years.items())) + '.\n')

def video_link(h):
    v = h['video']
    if not v: return '—'
    who = ' '.join(x for x in [STAGE.get(v['stage'] or '', ''), LEVEL.get(v['level'] or '', '')] if x)
    lock = ' 🔒' if (not v['playable'] or h['newest_unplayable']) else ''
    via = f" ({v['channel']})" if v.get('channel') else ''
    return f"[{v['year']} {who}]({v['url']}){via}{lock}"

def doubt(h):
    d = (h['note'].removeprefix('check: ').removeprefix('check').strip() or 'placement only') if 'check' in h['note'] else ''
    if h['status'] == 'new' and h['video'] and not h['video']['playable']: d = (d + '; ' if d else '') + 'its only video is unavailable: needs another source'
    return d

review = [h for h in hymns if doubt(h)]
L.append(f'## To review ({len(review)})\n')
if not review: L.append('Nothing to review: every placement is confirmed.\n')
if review: L.append('Confirm or correct the season and service of each, or say when two names are the same hymn. '
         'Corrections go in `tools/inventory/rules.py`. "Placement only" means the doubt is the season or service.\n')
if review: L.append('| Hymn | Arabic | Placed in | Doubt | Video |')
if review: L.append('|---|---|---|---|---|')
for h in review:
    L.append(f"| {h['english']} | {h['arabic']} | {' + '.join(p['english'] for p in h['places'])} | {doubt(h)} | {video_link(h)} |")
L.append('')

for g, col in groups:
    hs = by_coll.get(col['id'])
    if not hs: continue
    n_new = sum(1 for h in hs if h['status'] == 'new')
    L.append(f"## {col['titles']['english']} · {col['titles']['arabic']}\n")
    L.append(f"{len(hs)} hymns, {n_new} new.\n")
    L.append('| Hymn | Arabic | Service | Status | Latest video | Versions |')
    L.append('|---|---|---|---|---|---|')
    for h in hs:
        svc = h['places'][0]['english'].split(' · ', 1)[1]
        extra = [p['english'] for p in h['places'][1:]]
        if extra: svc += ' (also ' + ', '.join(extra) + ')'
        status = f"in app (`{h['app_id']}`)" if h['status'] == 'in app' else '**new**'
        ver = str(1 + len(h['other_versions'])) if h['video'] else ''
        name = h['english'] + (' ⚠' if doubt(h) else '')
        L.append(f"| {name} | {h['arabic']} | {svc} | {status} | {video_link(h)} | {ver} |")
    L.append('')

open(os.path.join(SITE, 'docs/app/hymn-inventory.md'), 'w').write('\n'.join(L))
print('written', len(L), 'lines')
